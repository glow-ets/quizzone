#!/usr/bin/env node
// Assembles MakeCode projects from firmware/src into firmware/dist:
//   dist/<name>/        a MakeCode project folder (pxt.json + files): push it to a GitHub repo
//                       and use "Import > Import URL" in https://makecode.microbit.org, or
//   dist/<name>.ts      one self-contained file: create a new project, switch to the
//                       JavaScript view, paste the whole file (Radio is built in).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PROJECTS } from './typecheck.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, '../src');
const dist = path.resolve(here, '../dist');
fs.rmSync(dist, { recursive: true, force: true });

const titles = {
  team: 'Contromossa quiz - team device',
  base: 'Contromossa quiz - base station (plug into the PC)',
  probe: 'Contromossa quiz - pin probe / self-test',
};
for (const [name, files] of Object.entries(PROJECTS)) {
  const dir = path.join(dist, name);
  fs.mkdirSync(dir, { recursive: true });
  const outFiles = [];
  let single = `// ${titles[name]}\n// Generated by firmware/tools/build.mjs - edit firmware/src instead.\n`;
  files.forEach((f, i) => {
    // main file must be called main.ts in a MakeCode project
    const outName = i === files.length - 1 ? 'main.ts' : f;
    fs.copyFileSync(path.join(src, f), path.join(dir, outName));
    outFiles.push(outName);
    single += `\n// ===== ${f} =====\n` + fs.readFileSync(path.join(src, f), 'utf8');
  });
  const usesRadio = name !== 'probe';
  fs.writeFileSync(path.join(dir, 'pxt.json'), JSON.stringify({
    name: `contromossa-${name}`,
    version: '0.1.0',
    description: titles[name],
    dependencies: usesRadio ? { core: '*', radio: '*' } : { core: '*' },
    files: ['README.md', ...outFiles],
    supportedTargets: ['microbit'],
    preferredEditor: 'tsprj',
  }, null, 4));
  fs.writeFileSync(path.join(dir, 'README.md'), `# ${titles[name]}\n\nPart of the Contromossa quiz system. See the repository README and docs/HARDWARE.md.\n`);
  fs.writeFileSync(path.join(dist, `${name}.ts`), single);
  console.log(`built dist/${name}/ and dist/${name}.ts`);
}
